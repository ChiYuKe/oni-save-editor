"""Bake the native AsteroidGridEntity idle_loop frame. Usage: script <ExportedProject>."""
import importlib.util,json,sys
from pathlib import Path
from PIL import Image
project=Path(__file__).resolve().parents[1];root=Path(sys.argv[1])/'Assets'
spec=importlib.util.spec_from_file_location('oni_kanim',project/'scripts/render-oni-kanims.py')
kanim=importlib.util.module_from_spec(spec);spec.loader.exec_module(kanim)
out=project/'public/assets/planets';out.mkdir(parents=True,exist_ok=True)
icons={};errors=[]
for build in sorted((root/'TextAsset').glob('*asteroid*_build.bytes')):
 name=build.name.removesuffix('_build.bytes')
 if name.startswith('shower_'):continue # Meteor shower overlay, not an asteroid body.
 anim=build.with_name(name+'_anim.bytes');png=root/'Texture2D'/(name+'_0.png')
 if not anim.exists() or not png.exists():continue
 try:
  frame=kanim.frame_for_bank(kanim.parse_anim(anim),'idle_loop')
  if frame is None:continue
  image,*_=kanim.render(png,kanim.parse_build(build),frame)
  box=image.getchannel('A').getbbox()
  if not box:raise ValueError('empty icon')
  image=image.crop(box);image.thumbnail((128,128),Image.Resampling.LANCZOS)
  image.save(out/(name+'.webp'),format='WEBP',lossless=True,method=6)
  icons[name+'_kanim']='/assets/planets/'+name+'.webp'
 except Exception as error:errors.append((name,str(error)))
assert 'asteroid_sandstone_start_kanim' in icons
assert 'aquatic_asteroid_so_kanim' in icons
(project/'src/lib/oniPlanetIcons.generated.ts').write_text('// Native AsteroidGridEntity idle_loop icons; generated by scripts/extract-oni-planet-icons.py.\nexport const ONI_PLANET_ICONS: Readonly<Record<string,string>> = '+json.dumps(icons,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'icons':len(icons),'bytes':sum((project/'public'/path.lstrip('/')).stat().st_size for path in icons.values()),'errors':errors}))
if errors:raise RuntimeError('Some planet icons failed to bake')
