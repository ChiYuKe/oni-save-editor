"""Generate pixel-identical WebP assets for static hosting (requires Pillow)."""
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
import io
import json
from PIL import Image
project=Path(__file__).resolve().parents[1]
public=project/'public'
roots=['assets/elements','assets/background/biomes','assets/render','assets/buildings/sprites']
paths=sorted(p for root in roots for p in (public/root).rglob('*.png') if p.stat().st_size >= (1048576 if 'buildings' in p.parts else 65536))
def convert(path):
 image=Image.open(path).convert('RGBA')
 if path.name in ['bgarray_liquids.png','bgarray_liquids_specular.png']:
  tile=image.width
  assert image.height==tile*16
  packed=Image.new('RGBA',(tile*4,tile*4))
  for n in range(16):packed.paste(image.crop((0,n*tile,tile,(n+1)*tile)),((n%4)*tile,(n//4)*tile))
  image=packed
 if max(image.size)>16383:return None
 data=io.BytesIO();image.save(data,format='WEBP',lossless=True,quality=75,method=4,exact=True)
 encoded=data.getvalue()
 if len(encoded)>=path.stat().st_size*.85:return None
 assert Image.open(io.BytesIO(encoded)).convert('RGBA').tobytes()==image.tobytes(),str(path)
 relative=path.relative_to(public)
 target=public/'assets/optimized'/relative.relative_to('assets').with_suffix('.webp')
 target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(encoded)
 return '/'+relative.as_posix(),'/'+target.relative_to(public).as_posix(),path.stat().st_size,len(encoded)
results=[]
with ThreadPoolExecutor(max_workers=2) as pool:
 for n,future in enumerate(as_completed([pool.submit(convert,path) for path in paths]),1):
  result=future.result()
  if result:results.append(result)
  if n%30==0:print(f'Checked {n}/{len(paths)} images',flush=True)
mapping={source:target for source,target,_,_ in sorted(results)}
(project/'src/lib/oniWebAssets.generated.ts').write_text('// Generated by scripts/generate-oni-web-assets.py; lossless, pixel verified.\nexport const ONI_WEB_ASSETS: Readonly<Record<string, string>> = '+json.dumps(mapping,indent=2)+'\n',encoding='utf-8')
print(json.dumps(dict(images=len(results),originalBytes=sum(x[2] for x in results),webBytes=sum(x[3] for x in results))))
