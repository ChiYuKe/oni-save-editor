"""Bundle small first-view artwork; full-resolution originals remain available on zoom."""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
from PIL import Image
import json
project=Path(__file__).resolve().parents[1];public=project/'public'
core=[p for folder in ['elements','render','background/biomes'] for p in (public/'assets'/folder).rglob('*.png') if p.name!='mask_atlas.png']
objects=[p for p in (public/'assets/buildings').rglob('*.png') if not any(part in ['tiles','utilities'] for part in p.relative_to(public/'assets/buildings').parts[:-1])]
def small(path):
 im=Image.open(path).convert('RGBA')
 if path.name in ['bgarray_liquids.png','bgarray_liquids_specular.png']:
  tile=im.width;packed=Image.new('RGBA',(128,128))
  for n in range(16):packed.paste(im.crop((0,n*tile,tile,(n+1)*tile)).resize((32,32),Image.Resampling.LANCZOS),((n%4)*32,(n//4)*32))
  im=packed
 else:im.thumbnail((128,128) if 'biomes' in path.parts else (16,16) if 'buildings' in path.parts else (64,64),Image.Resampling.LANCZOS)
 return '/'+path.relative_to(public).as_posix(),im
with ThreadPoolExecutor(max_workers=2) as pool:images=list(pool.map(small,core+objects))
images.sort(key=lambda entry:(-entry[1].height,-entry[1].width,entry[0]))
rects={};x=y=row=0;width=1024
for path,im in images:
 if x+im.width>width:y+=row;x=0;row=0
 rects[path]=[x,y,im.width,im.height];x+=im.width;row=max(row,im.height)
atlas=Image.new('RGBA',(width,y+row))
for path,im in images:atlas.paste(im,tuple(rects[path][:2]))
out=public/'assets/preview/world.webp';out.parent.mkdir(parents=True,exist_ok=True)
atlas.save(out,format='WEBP',lossless=False,quality=78,method=4,alpha_quality=100)
assert Image.open(out).getchannel('A').tobytes()==atlas.getchannel('A').tobytes()
(project/'src/lib/oniPreviewAtlas.generated.ts').write_text('// Generated by scripts/generate-oni-preview-atlas.py.\nexport const ONI_PREVIEW_ATLAS = { path: "/assets/preview/world.webp", rects: '+json.dumps(rects,separators=(',',':'))+' } as const\n',encoding='utf-8')
print(dict(images=len(images),size=atlas.size,bytes=out.stat().st_size),flush=True)

# Keep startup independent of a second, large metadata download.
manifest=json.loads((public/'assets/buildings/manifest.json').read_text(encoding='utf-8'))
fields={'path','widthCells','heightCells','anchorOffsetXCells','anchorOffsetYCells','verticalOffsetCells'}
lean={key:{name:value for name,value in item.items() if name in fields} for key,item in manifest.items()}
(project/'src/lib/oniBuildingSprites.generated.ts').write_text('// Generated by scripts/generate-oni-preview-atlas.py.\nexport const ONI_BUILDING_SPRITES: Record<string, {path: string; widthCells: number; heightCells?: number; anchorOffsetXCells?: number; anchorOffsetYCells?: number; verticalOffsetCells?: number}> = '+json.dumps(lean,separators=(',',':'))+'\n',encoding='utf-8')
