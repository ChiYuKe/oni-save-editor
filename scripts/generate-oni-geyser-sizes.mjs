import { readdir, readFile, writeFile } from 'node:fs/promises'
const dir=new URL('../public/assets/geysers/',import.meta.url),sizes={}
for(const name of (await readdir(dir)).filter(n=>n.endsWith('.png')).sort()){
 const bytes=await readFile(new URL(name,dir))
 if(bytes.subarray(0,8).toString('hex')!=='89504e470d0a1a0a')throw Error(`Invalid PNG: ${name}`)
 sizes[name]=[bytes.readUInt32BE(16),bytes.readUInt32BE(20)]
}
await writeFile(new URL('../src/lib/oniGeyserImageSizes.generated.ts',import.meta.url),'// Native PNG dimensions; generated by scripts/generate-oni-geyser-sizes.mjs.\nexport const ONI_GEYSER_IMAGE_SIZES: Record<string, readonly [number, number]> = '+JSON.stringify(sizes,null,2)+'\n')
